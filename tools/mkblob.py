#!/usr/bin/env python3
"""Turn a binary file into a C source file with a const array + size symbol.

Usage: mkblob.py IN OUT ARRAY_NAME SIZE_NAME
"""
import sys

src, dst, name, size_name = sys.argv[1:5]
data = open(src, 'rb').read()

with open(dst, 'w', newline='') as f:
    f.write('/* generated by tools/mkblob.py; do not edit */\n')
    f.write('const unsigned char %s[] = {\n' % name)
    for i in range(0, len(data), 16):
        f.write('\t' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
    f.write('const unsigned long %s = %dUL;\n' % (size_name, len(data)))
print('%s: %d bytes -> %s' % (name, len(data), dst))
